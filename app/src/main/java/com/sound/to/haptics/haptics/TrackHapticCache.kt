package com.sound.to.haptics.haptics

import android.content.Context
import java.io.File
import java.security.MessageDigest

/**
 * On-disk cache for per-track haptic-enabled OGG files. Keyed by hashed
 * BitChord videoId so repeated plays of the same track skip re-capture and
 * re-encode. Each cached file is a genuine playable OGG (produced by
 * HapticCaptureConverter, same format as offline mode's output) rather
 * than the raw vibration-envelope format used before.
 */
class TrackHapticCache(context: Context) {

    private val dir = File(context.filesDir, "bitchord_haptics_v${HapticProcessing.VERSION}").apply {
        // Haptic algorithm versions are not interchangeable. Remove old
        // cache directories at startup instead of silently replaying
        // a pre-layering profile generated by an obsolete pipeline.
        context.filesDir.listFiles()
            ?.filter {
                it.isDirectory &&
                    it.name.startsWith("bitchord_haptics") &&
                    it.absolutePath != absolutePath
            }
            ?.forEach { it.deleteRecursively() }
        mkdirs()
        // A process death can leave an encoder scratch file behind. It is
        // never a playable cache entry, so remove it during startup instead
        // of letting invisible temp data grow indefinitely.
        listFiles()
            ?.filter {
                it.name.endsWith(".tmp", ignoreCase = true) ||
                    it.name.endsWith(".encoding.tmp.ogg", ignoreCase = true)
            }
            ?.forEach { it.delete() }
    }

    private fun keyFor(trackId: String): String {
        val digest = MessageDigest.getInstance("SHA-256").digest(trackId.toByteArray())
        return digest.joinToString("") { "%02x".format(it) }.take(24)
    }

    fun fileFor(trackId: String): File = File(dir, "${keyFor(trackId)}.ogg")

    /** Persistent copy of the downloaded audio rendition, so re-tapping a
     *  converted track never hits the network again. */
    fun audioFileFor(trackId: String): File = File(dir, "${keyFor(trackId)}.audio")

    fun audioExists(trackId: String): Boolean =
        audioFileFor(trackId).let { it.exists() && it.length() > 262_144L }

    fun exists(trackId: String): Boolean = fileFor(trackId).let { it.exists() && it.length() > 0 }

    fun scratchPcmFile(trackId: String): File = File(dir, "${keyFor(trackId)}.pcm.tmp")

    fun analysisFile(trackId: String): File = File(dir, "${keyFor(trackId)}.layers")

    /** Sidecar timeline for the transient engine ([loadTransientAnalysis]). */
    fun transientAnalysisFile(trackId: String): File = File(dir, "${keyFor(trackId)}.transient")

    fun delete(trackId: String) {
        fileFor(trackId).takeIf { it.exists() }?.delete()
        analysisFile(trackId).takeIf { it.exists() }?.delete()
        transientAnalysisFile(trackId).takeIf { it.exists() }?.delete()
        audioFileFor(trackId).takeIf { it.exists() }?.delete()
    }

    fun clearAll() {
        dir.listFiles()?.forEach { it.delete() }
    }
}
